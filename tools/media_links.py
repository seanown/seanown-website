def org_slug(org):
    """機構名 → 條目頁錨點（與 build_wiki.py 的 pos id 規則一致）。"""
    s = org
    for ch in "／/・·（）()，,。":
        s = s.replace(ch, "-")
    out = []
    for c in s:
        if c.isalnum() or c in "-_":
            out.append(c.lower())
    return "".join(out).strip("-")


def media_org_map():
    """回傳 {media_title: org_slug}"""
    return {k: org_slug(v) for k, v in LINKS.items() if k}