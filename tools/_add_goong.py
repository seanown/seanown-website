BODY = """很多人以為，澳門在影視作品裡只能是「借個賭場大廳拍兩個鏡頭就走」的背景板。但早在二〇〇六年，一齣紅遍亞洲的韓國偶像劇，就已經把整座澳門當成了愛情童話的終章。這也是為什麼，一部「不是電影」的韓劇，會出現在我們的澳門電影專輯裡——它比我們今天談的「跟著電影遊澳門」，早了將近二十年。

《宮》（Goong，英文 Princess Hours）是二〇〇六年 MBC 的水木劇（韓國每週三、四晚間播出的電視劇），共二十四集，自一月十一日播到三月三十日，由黃仁雷導演、仁恩雅編劇，尹恩惠飾演被迫嫁入皇室的平民女孩申采靜、朱智勳飾演皇太子李信、金楨勳飾演表兄李律、宋智孝飾演閔孝琳。它在韓國創下近三成收視峰值，是當年年度冠軍，也把「皇室偶像劇」這個類型打到全亞洲都在追。對我們而言，它的意義不在於收視，而在於它證明了一件事：澳門可以不是別人故事的過場，而是愛情童話的「結局本身」。這件事，對我們今天向旅遊局爭取資源、推動影視文旅，是一個早了快二十年的先例。

故事並不複雜，卻足夠讓人入戲。在《宮》的設定裡，大韓民國仍然保留君主制，皇室的李家握有象徵性的地位。皇太子李信從小被逼著承擔繼位重任，個性冷峻；平民出身的美術系大學生申采靜，原本有著自己的男友與人生規劃，卻因為祖上與皇室早有婚約，被迫嫁入宮中，成為皇太子妃。一場政治聯姻，寫的是兩個陌生年輕人從抗拒、磨合到相愛的過程；也是一場宮廷權力鬥爭——李信與表兄李律之間的皇位繼承之爭，以及采靜與閔孝琳之間友情與競爭交織的關係。幾經波折，這對夫妻的情感走到十字路口，而全劇的大結局，選擇讓他們逃離宮牆、遠走他方。

那個「他方」，就是澳門。

二〇〇六年三月二十五日至二十七日，五十多人的劇組來澳拍了三天，澳門旅遊局當時還出面協助。他們走過的，是一張幾乎可以當成旅遊地圖的清單：大三巴牌坊、路環黑沙海灘、竹灣海灘、民政總署大樓、十月初五馬路、恩尼斯總統前地、安德魯餅店，以及路環水鴨街八號的里斯本地帶餐廳；而全劇最關鍵的一場——李信與采靜在路環聖方濟各聖堂舉行婚禮——把澳門的南歐小鎮氣息，直接拍成了童話的終章。劇組還入住路環黑沙馬路一九一八號的澳門威斯汀度假酒店。換句話說，這不是「來澳門取個景」，而是「把澳門寫進了愛情的結局裡」。

戲裡有句話，我一直記得。采靜站在澳門的街巷之間，說：「澳門是西方與東方交融的地方……我真是來對地方了。」另一頭，李信在第15集那句「沒有你，我會活下去嗎？」也成了整部劇最被傳誦的台詞之一。這兩句，一句講的是澳門這座城，一句講的是這座城裡發生的愛情——它們恰好說清了《宮》與澳門的關係：城，是東西交融的容器；戲，是在這容器裡完成的承諾。

講到這裡，就不能不談韓國人有多會把影視融進旅遊。韓國的影視觀光不是偶發的，而是一整套國家級的打法。最早的經典案例，是二〇〇二年《冬季戀歌》帶旺的南怡島，一座本來普通的江原道小島，因為劇中男女主角的約定，成了韓國國民與海外粉絲的朝聖地；釜山甘川洞文化村、濟州 Olle 步道、黑山島，也都因影視作品而被重新「發明」成景點。這套模式被稱為 Hallyu 3.0——從 K-Drama 直接過渡到 K-Tourism。韓國政府有「K-Culture Roadmap」，把食、影、俗串成一條線，目標是二〇二六年吸引三千萬旅客；自二〇二一年以來，文化觀光收入成長將近五成。這一切的源頭，是金大中政府一九九八年提出的「文化立國」，隔年推出《文化產業振興基本法》，在文化體育觀光部底下設內容政策局，並在海外二十多國設了三十多處文化院。一句話總結：在韓國，影視從來不是拍完就結束，而是觀光的起跑點。

我對這件事有特別切身的理解。今年（二〇二六）我去了一趟張家界，最震撼的不是山，而是山裡的韓國人——滿山滿谷，幾乎比本國遊客還顯眼。回來一查才恍然：這股風潮，竟然也是影視一句話帶起來的。二〇〇一年，韓國觀光公社社長趙洪奎到訪張家界，留下了那句著名的宣傳語：「人生不到张家界，百岁岂能称老翁」，從此把張家界綁定在韓國人的「孝道旅遊」上。旅行社的話術更直白：「不孝有三，不送父母去張家界為大。」數據更驚人：每四名到中國大陸旅遊的韓國人，就有一名去了張家界，張家界早已是韓國人赴華旅遊的第一目的地；而六十五歲以上的韓國老人，將近四成曾到訪張家界——對他們來說，帶父母去一趟張家界，是子女盡孝的標準動作。

而最近這一波，是另一句台詞點燃的。二〇二五年 Netflix 韓劇《苦盡柑來遇見你》（IU 與朴寶劍主演，豆瓣高達九點多分）結尾，男女主角約定「明年我们去张家界看落叶」，這句話瞬間在韓國炸開，赴張家界看秋天落葉成了新世代的浪漫儀式。更早之前，二〇〇九年《阿凡達》裡的哈里路亞山被認出是張家界的乾坤柱，二〇一六年韓綜《團結才能火》做過張家界特輯，二〇〇四年中韓合拍片《九天半》在此取景，韓劇《我的大叔》也提及張家界。結果是：張家界二〇二四年接待入境旅客一百八十三萬人次，年增超過一倍六，韓國是其最大的境外客源，當地甚至設了韓文指示牌、配韓語導遊、接受韓幣結算。

這就是「影視語言轉譯成旅遊行動」的力量——一句台詞，可以讓一座山成為全民朝聖地。分量之重，故事之綿長，值得我們好好借鏡。

事實上，澳門對韓國影視一直很有吸引力，《竊盜同盟》《花樣男子》等作品都曾來澳門取景，一張「韓國影視在澳門」的地圖早已存在，只是我們過去沒有去盤點、去轉譯、去串成路線。

那麼，澳門能從韓國身上學到什麼？我認為至少有五件事。第一，把地標「場景化」而不是「背景化」——《宮》拍的不是「澳門的教堂」，而是「在澳門教堂裡完成的婚禮」，情感落點在場景裡，遊客才會想重走。第二，政府主動協助劇組——澳門旅遊局二〇〇六年就做過的事，今天更該制度化，把「協助取景」變成招商工具。第三，把食、影、俗串成路線：采靜吃過的安德魯蛋撻、走過的十月初五馬路、福隆新街的老旅館，本來就能連成一條「韓劇迷的澳門一日遊」。第四，用一句金句、一個場景去定義一座城——就像「明年去張家界看落葉」那樣，我們也該幫澳門找到屬於自己的那句話。第五，主動爭取韓流與國際劇組來澳，把我們寫進別人的童話結局裡，再把它變成自己的文旅資產。

## 散場之後

寫完這篇，我想起的竟是采靜站在澳門街頭說的那句話——「我真是來對地方了」。二十年前，《宮》用三天的拍攝，把澳門拍成了童話的結局；那時候大概沒人想到，這會是一堂關於「影視如何帶動旅遊」的早課。今年我在張家界看見滿山的韓國人，才真正明白那句話的分量：一座城被認真地拍進故事裡，它就不再只是地圖上的一個點，而會變成無數人想親自走一遭的理由。我們手上的澳門，本來就是東西交融的活樣本，比誰都適合被寫進故事。今天我們要做的，不是等別人來拍，而是主動把更多這樣的童話，寫進澳門自己的文旅提案裡。這一次，輪到我們來說那句「來對地方了」。"""

